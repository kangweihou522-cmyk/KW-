const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const { createLibraryStore } = require('../electron/backend/libraryStore.cjs');
const { createLibraryCommands } = require('../electron/backend/libraryCommands.cjs');

test('journal details, editable IF and multiple tags survive reload, snapshots and partial updates', async t => {
  const dataDir = await fs.mkdtemp(path.join(os.tmpdir(), 'paperdesk-metadata-'));
  const appPaths = { dataDir, configPath: path.join(dataDir, 'config.json'), libraryPath: path.join(dataDir, 'library.json'), libraryDatabasePath: path.join(dataDir, 'library.sqlite') };
  let store = createLibraryStore(appPaths);
  t.after(async () => { store.close(); await fs.rm(dataDir, { recursive: true, force: true }); });
  const commands = () => createLibraryCommands({ appPaths, store });
  const file = path.join(dataDir, 'original.pdf');
  await fs.writeFile(file, '%PDF-1.4\nOriginal evidence');
  const [imported] = await commands().library_import_pdfs({ request: { paths: [file], importMode: 'keep' } });
  const paperId = imported.paper.id;
  await commands().library_update_paper({ request: { paperId, publication: 'Fictional Journal', volume: '13', issue: '2', pages: '112–124', publishedDate: '2025-03-12', impactFactor: 12.3, tags: ['益生菌', '屏障功能', '待精读', '益生菌'] } });
  store.close(); store = createLibraryStore(appPaths);
  const saved = store.load().papers[0];
  assert.equal(saved.publication, 'Fictional Journal');
  assert.equal(saved.volume, '13'); assert.equal(saved.issue, '2'); assert.equal(saved.pages, '112–124');
  assert.equal(saved.publishedDate, '2025-03-12'); assert.equal(saved.impactFactor, 12.3);
  assert.deepEqual(saved.tags.map(tag => tag.name), ['益生菌', '屏障功能', '待精读']);
  assert.deepEqual((await commands().library_list_tags()).map(tag => tag.name).sort(), ['益生菌', '屏障功能', '待精读'].sort());
  await commands().library_update_paper({ request: { paperId, tags: ['益生菌', '机制研究'] } });
  const updated = store.load().papers[0];
  assert.equal(updated.impactFactor, 12.3);
  assert.equal(updated.tags[0].id, saved.tags[0].id);
  assert.deepEqual(updated.tags.map(tag => tag.name), ['益生菌', '机制研究']);
  const snapshot = path.join(dataDir, 'snapshot.sqlite');
  store.snapshotTo(snapshot);
  const restored = store.loadFromSnapshot(snapshot).papers[0];
  assert.equal(restored.impactFactor, 12.3); assert.equal(restored.volume, '13');
  assert.deepEqual(restored.attachments, saved.attachments);
  assert.equal(await fs.readFile(file, 'utf8'), '%PDF-1.4\nOriginal evidence');
  for (const invalid of [-1, NaN, Infinity, '12']) await assert.rejects(commands().library_update_paper({ request: { paperId, impactFactor: invalid } }), /影响因子/);
  assert.equal(store.load().papers[0].impactFactor, 12.3);
  await commands().library_update_paper({ request: { paperId, impactFactor: 0 } });
  assert.equal(store.load().papers[0].impactFactor, 0);
  await commands().library_update_paper({ request: { paperId, impactFactor: null, tags: [] } });
  assert.equal(store.load().papers[0].impactFactor, null);
  assert.deepEqual(store.load().papers[0].tags, []);
});
